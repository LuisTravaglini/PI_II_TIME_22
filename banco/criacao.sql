-- Estrutura proposta para o TRAK, para executar em um esquema Oracle vazio.
-- Revisar em equipe antes de executar: CREATE TABLE altera o banco.
CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(120) NOT NULL,
    email VARCHAR2(200) NOT NULL UNIQUE,
    senha VARCHAR2(255) NOT NULL,
    perfil VARCHAR2(30) NOT NULL
);

CREATE TABLE projetos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150) NOT NULL
);

CREATE TABLE demandas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR2(200) NOT NULL,
    descricao VARCHAR2(4000) NOT NULL,
    tipo VARCHAR2(30) NOT NULL,
    prioridade VARCHAR2(20) NOT NULL,
    status VARCHAR2(20) NOT NULL,
    projeto_id NUMBER NOT NULL REFERENCES projetos(id),
    responsavel_id NUMBER REFERENCES usuarios(id),
    data_criacao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    prazo DATE
);

CREATE TABLE comentarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id NUMBER NOT NULL REFERENCES demandas(id),
    usuario_id NUMBER NOT NULL REFERENCES usuarios(id),
    texto VARCHAR2(4000) NOT NULL,
    data_hora TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE historico_alteracoes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id NUMBER NOT NULL REFERENCES demandas(id),
    usuario_id NUMBER NOT NULL REFERENCES usuarios(id),
    campo VARCHAR2(50) NOT NULL,
    valor_anterior VARCHAR2(4000),
    valor_novo VARCHAR2(4000),
    data_hora TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
